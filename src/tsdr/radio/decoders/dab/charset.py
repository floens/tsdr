def decode_charset(raw: bytes, charset: int) -> str:
    """Decode bytes to string using a DAB charset identifier."""
    if charset == 0x0F:
        return raw.decode("utf-8", errors="replace")
    if charset == 0x06:
        return raw.decode("utf-16-be", errors="replace")
    return "".join(chr(_EBU_LATIN_TO_UCS2[b]) for b in raw)
