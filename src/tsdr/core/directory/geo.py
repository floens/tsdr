@lru_cache(maxsize=2048)
def country_code(lat: float, lon: float) -> str | None:
    """Approximate ISO-3166-1 alpha-2 country code for a coordinate, or None."""
    for code, lat_min, lat_max, lon_min, lon_max in _COUNTRY_BOXES:
        if lat_min <= lat <= lat_max and lon_min <= lon <= lon_max:
            return code
    return None
